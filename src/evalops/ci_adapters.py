"""Generated CI adapters: GitHub Actions, GitLab CI, Azure Pipelines and Jenkins from one template.

``make ci-adapters`` rewrites the four committed files under ``ci/`` from this module, exactly the
way ``make schema`` rewrites ``docs/evalops.schema.json`` and ``make capabilities`` rewrites
``docs/CAPABILITIES.md``: the committed files are build artifacts, and
``tests/unit/test_ci_adapters.py`` fails when one of them drifts from the template.

The adapters carry **no stage logic**. Every stage runs through the hand-written shim
``bash ci/pipeline.sh <stage>`` (``ci/pipeline.sh`` execs ``evalops pipeline``), and the stage names
come from :data:`evalops.pipeline.STAGES`, so a stage added to the pipeline and forgotten here turns
the parity test red instead of being silently skipped in CI. What this module does own is the
*binding*: which platform event fires a stage, the platform-native condition that selects it, and
the env vars it plumbs (``EVALOPS_PR``/``EVALOPS_BRANCH`` for a pull request, ``EVIDENCE_GROUP`` for
a release). That table is :data:`BINDINGS`; rendering is a mechanical translation of it into each
platform's syntax, so the four files cannot drift apart from each other or from the pipeline.

Rendering is deterministic and offline: no timestamps, no hostnames, no environment reads.
"""

