# ---------------------------------------------------------------------------
# CLI surface (B)
# ---------------------------------------------------------------------------
def adapter_payload() -> dict[str, Any]:
    """``evalops ci-adapters --json`` data: one entry per adapter, sorted by name, nothing written."""
    return {
        "adapters": [
            {
                "name": spec.name,
                "path": spec.path,
                "stages": list(pipeline.STAGES),
                "bytes": len(spec.render().encode("utf-8")),
            }
            for spec in sorted(ADAPTERS.values(), key=lambda spec: spec.name)
        ]
    }


def write_adapters(root: pathlib.Path | str | None = None) -> list[str]:
    """Render all four adapters under ``root`` (default: the repo root) and return the written paths."""
    base = REPO_ROOT if root is None else pathlib.Path(root)
    written: list[str] = []
    for spec in ADAPTERS.values():
        target = base / spec.path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(spec.render(), encoding="utf-8")
        written.append(str(target))
    return sorted(written)


def command_payload(*, write: bool, directory: str | None) -> dict[str, Any]:
    """The command's payload: a report by default, the four files with ``write``.

    ``directory`` defaults to the repo root (so ``ci/...`` lands in ``ci/``); a path that is not a
    directory is exit 2, and nothing but the four spec'd files is ever written.
    """
    if not write:
        payload = adapter_payload()
        return {
            "summary": f"{len(payload['adapters'])} CI adapters, generated from pipeline.STAGES "
            "(report only; --write regenerates them)",
            **payload,
        }
    root = REPO_ROOT if directory is None else pathlib.Path(directory)
    if not root.is_dir():
        raise EvalOpsError(f"--dir {root} does not exist or is not a directory", EXIT_USAGE, {"path": str(root)})
    files = write_adapters(root)
    return {"summary": f"wrote {len(files)} CI adapters under {root}", "files_written": files}
