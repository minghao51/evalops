# ---------------------------------------------------------------------------
# the one shared binding table (A2): stage -> trigger + condition + env plumbing
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class Binding:
    """One ``(adapter, stage)`` binding: *when* a stage runs and *what* it is given.

    Every field is a binding, never behaviour (A3): ``trigger`` is the platform event that fires the
    stage, ``when`` the platform-native condition that selects it, ``env`` the exported name/value
    pairs, ``setup`` the checkout plumbing lines (``git`` only), ``group``/``cancel_in_progress``
    the concurrency key, ``environment`` a protected deployment target, and ``report`` names the
    file the platform surfaces (step summary / PR comment). No adapter may infer stage behaviour
    from any of it: the shim decides what a stage does.
    """

    stage: str
    trigger: str
    when: str
    env: tuple[tuple[str, str], ...] = ()
    setup: tuple[str, ...] = ()
    checkout: tuple[str, ...] = ()
    group: str | None = None
    cancel_in_progress: bool = False
    environment: str | None = None
    report: str | None = None
    comment: bool = False
    artifacts: bool = True
    manual: bool = False
    note: tuple[str, ...] = ()


