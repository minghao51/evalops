def binding(adapter: str, stage: str) -> Binding:
    """The binding for one ``(adapter, stage)`` pair; a stage with no row is a template defect."""
    try:
        return BINDINGS[adapter][stage]
    except KeyError:
        raise KeyError(f"no {adapter} CI binding for pipeline stage {stage!r}: add it to BINDINGS") from None


# ---------------------------------------------------------------------------
# rendering helpers
# ---------------------------------------------------------------------------
def _header(marker: str) -> list[str]:
    return [f"{marker} {GENERATED_BY}"]


def _comment(marker: str, lines: tuple[str, ...] | list[str]) -> list[str]:
    return [f"{marker} {line}".rstrip() for line in lines]


def _note(marker: str, item: Binding) -> list[str]:
    """The stage's binding comment: the event that fires it, plus any documented caveat."""
    return _comment(marker, [f"{item.stage} stage, fired by {item.trigger}.", *item.note])


def _env_block(indent: str, env: tuple[tuple[str, str], ...]) -> list[str]:
    return [f"{indent}{name}: {value}" for name, value in env]


def _shim_line(item: Binding, *, env_prefix: bool = False) -> str:
    """The one evalops invocation a rendered adapter may contain (A3)."""
    prefix = " ".join(f"{name}={value}" for name, value in item.env) + " " if env_prefix and item.env else ""
    return f"{prefix}{SHIM} {item.stage}"


# ---------------------------------------------------------------------------
# GitHub Actions
# ---------------------------------------------------------------------------
def _render_github() -> str:
    lines = [
        *_header("#"),
        "# Copy to .github/workflows/evalops.yml. Backend = repo variable EVALOPS_ENV (mlflow, databricks,",
        "# langfuse, langsmith, logfire, local...). Only the secrets your backend needs must be set.",
        "name: evalops",
        "on:",
        "  pull_request:",
        f"  push: {{ branches: [{pipeline.DEFAULT_BRANCH}] }}",
        f'  schedule: [{{ cron: "{CRON}" }}]',
        "  workflow_dispatch:",
        "    inputs:",
        f'      {EVIDENCE_INPUT}: {{ description: "{EVIDENCE_DESCRIPTION}", required: true }}',
        "",
        "permissions: { contents: write, pull-requests: write, id-token: write }",
        "",
        "env:",
    ]
    for name, value, comment in GITHUB_ENV:
        lines.append(f"  {name}: {value}" + (f"  # {comment}" if comment else ""))
    lines += ["", "jobs:"]
    for index, stage in enumerate(pipeline.STAGES):
        item = binding("github", stage)
        job_env = tuple((name, value) for name, value in item.env if name not in GITHUB_STEP_ENV)
        step_env = tuple((name, value) for name, value in item.env if name in GITHUB_STEP_ENV)
        if index:
            lines.append("")
        lines += [*_note("  #", item), f"  {stage}:", f"    if: {item.when}", "    runs-on: ubuntu-latest"]
        if item.group:
            cancel = ", cancel-in-progress: true" if item.cancel_in_progress else ""
            lines.append(f"    concurrency: {{ group: {item.group}{cancel} }}")
        if item.environment:
            lines.append(f"    environment: {item.environment}  # configure required reviewers here")
        if job_env:
            lines += ["    env:", *_env_block("      ", job_env)]
        lines += ["    steps:", "      - uses: actions/checkout@v4"]
        if item.checkout:
            lines.append(f"        with: {{ {', '.join(item.checkout)} }}")
        lines += [
            "      - uses: actions/setup-python@v5",
            f'        with: {{ python-version: "{PYTHON_VERSION}" }}',
            f"      - run: {PIP_INSTALL['github']}",
            f"      - run: {_shim_line(item)}",
        ]
        if step_env:
            lines.append(f"        env: {{ {', '.join(f'{name}: {value}' for name, value in step_env)} }}")
        if item.report:
            report = f"{OUTPUT_DIR}/{item.report}"
            if item.comment:
                lines += [
                    f"      - if: always() && hashFiles('{report}') != ''",
                    f"        run: gh pr comment ${{{{ github.event.pull_request.number }}}} --body-file {report}",
                    '        env: { GH_TOKEN: "${{ github.token }}" }',
                ]
            else:
                lines += ["      - if: always()", f'        run: cat {report} >> "$GITHUB_STEP_SUMMARY" || true']
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# GitLab CI
# ---------------------------------------------------------------------------
def _render_gitlab() -> str:
    lines = [
        *_header("#"),
        "# Copy to .gitlab-ci.yml. Set EVALOPS_ENV + backend credentials as CI/CD variables.",
        f"image: python:{PYTHON_VERSION}",
        'variables: { EVALOPS_ENV: "local", PIP_EXTRAS: "" }',
        "before_script:",
        f"  - {PIP_INSTALL['gitlab']}",
    ]
    for stage in pipeline.STAGES:
        item = binding("gitlab", stage)
        manual = ", when: manual" if item.manual else ""
        lines += ["", f"evalops:{stage}:", *_note("  #", item)]
        lines.append(f"  rules: [{{ if: {item.when}{manual} }}]")
        if item.group:
            lines.append(f"  resource_group: {item.group}")
        if item.environment:
            hint = "# protect for approvals" + (f"; set {EVIDENCE_GROUP} when triggering" if item.manual else "")
            lines.append(f"  environment: {{ name: {item.environment} }}  {hint}")
        if item.env:
            lines += ["  variables:", *_env_block("    ", item.env)]
        lines += ["  script:", *(f"    - {line}" for line in item.setup), f"    - {_shim_line(item)}"]
        if item.artifacts:
            lines.append(f"  artifacts: {{ when: always, paths: [{OUTPUT_DIR}/] }}")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Azure Pipelines
# ---------------------------------------------------------------------------
def _render_azure() -> str:
    lines = [
        *_header("#"),
        "# Copy to azure-pipelines.yml. For release approvals, move the release step into a deployment",
        f'# job targeting an Azure DevOps environment named "{PROTECTED_ENV}" with required approvers.',
        f"trigger: {{ branches: {{ include: [{pipeline.DEFAULT_BRANCH}] }} }}",
        'pr: { branches: { include: ["*"] } }',
        "schedules:",
        f'  - cron: "{CRON}"',
        f"    branches: {{ include: [{pipeline.DEFAULT_BRANCH}] }}",
        "    always: true",
        "parameters:",
        '  - { name: evidenceGroup, type: string, default: "" }',
        "",
        "pool: { vmImage: ubuntu-latest }",
        'variables: { EVALOPS_ENV: local, PIP_EXTRAS: "" }',
        "",
        "steps:",
        "  - checkout: self",
        "    persistCredentials: true",
        f"    {FETCH_DEPTH_AZURE}",
        "  - task: UsePythonVersion@0",
        f'    inputs: {{ versionSpec: "{PYTHON_VERSION}" }}',
        f"  - script: {PIP_INSTALL['azure']}",
    ]
    for stage in pipeline.STAGES:
        item = binding("azure", stage)
        lines += [*_note("  #", item)]
        if item.setup:
            lines.append("  - script: |")
            lines += [f"      {line}" for line in (*item.setup, _shim_line(item, env_prefix=True))]
        else:
            lines.append(f"  - script: {_shim_line(item, env_prefix=True)}")
        lines.append(f"    condition: {item.when}")
    lines += [f"  - publish: {OUTPUT_DIR}", "    artifact: evalops", "    condition: always()"]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Jenkins (declarative pipeline)
# ---------------------------------------------------------------------------
def _render_jenkins() -> str:
    lines = [
        *_header("//"),
        '// Copy to a Jenkins "Pipeline script from SCM" job (Script Path: ci/Jenkinsfile). The Git SCM',
        f"// plugin's default clone is full (shallow: false) -- the same full history {FETCH_DEPTH_GITHUB} asks",
        "// for elsewhere, and what the pipeline needs to diff a baseline commit.",
        f"// {FROZEN_CHANGE} is not derived here: Jenkins exposes no change-request labels without a",
        f"// plugin -- set the documented boolean build parameter when `{APPROVED_LABEL}` applies.",
        "pipeline {",
        "  agent any",
        "",
        f"  triggers {{ cron('{CRON}') }}",
        "",
        "  parameters {",
        f"    string(name: '{EVIDENCE_GROUP}', defaultValue: '', description: '{EVIDENCE_DESCRIPTION}')",
        f"    booleanParam(name: '{FROZEN_CHANGE}', defaultValue: false,",
        f"      description: 'set when `{APPROVED_LABEL}` is approved for this build')",
        "  }",
        "",
        "  environment {",
        "    EVALOPS_ENV = 'local'",
        "    PIP_EXTRAS = ''",
        f'    {FROZEN_CHANGE} = "${{params.{FROZEN_CHANGE}}}"',
        "  }",
        "",
        "  stages {",
    ]
    for stage in pipeline.STAGES:
        item = binding("jenkins", stage)
        lines += [
            *_note("    //", item),
            f"    stage('{stage}') {{",
            f"      when {{ {item.when} }}",
            "      steps {",
            f"        sh '{PIP_INSTALL['jenkins']}'",
        ]
        if item.env:
            pairs = ", ".join(f'"{name}={value}"' for name, value in item.env)
            lines += [f"        withEnv([{pairs}]) {{", f"          sh '{_shim_line(item)}'", "        }"]
        else:
            lines.append(f"        sh '{_shim_line(item)}'")
        lines.append("      }")
        if item.artifacts:
            lines.append(
                f"      post {{ always {{ archiveArtifacts artifacts: '{OUTPUT_DIR}/**', allowEmptyArchive: true }} }}"
            )
        lines.append("    }")
    lines += ["  }", "}", ""]
    return "\n".join(lines)


